/// Supported application languages.
enum AppLanguage { en, fr, ar }

extension AppLanguageX on AppLanguage {
  String get code {
    switch (this) {
      case AppLanguage.en:
        return 'en';
      case AppLanguage.fr:
        return 'fr';
      case AppLanguage.ar:
        return 'ar';
    }
  }

  String get label {
    switch (this) {
      case AppLanguage.en:
        return 'English';
      case AppLanguage.fr:
        return 'Français';
      case AppLanguage.ar:
        return 'العربية';
    }
  }

  String get flag {
    switch (this) {
      case AppLanguage.en:
        return '🇧';
      case AppLanguage.fr:
        return '🇫🇷';
      case AppLanguage.ar:
        return '🇸';
    }
  }

  Locale get locale => Locale(code);

  bool get isRtl => this == AppLanguage.ar;
}

